"""Regenerate plugins/stockdex/skills/stockdex/reference/metrics.md from stockdex.config.

Usage: python scripts/generate_skill_metrics.py
"""

from pathlib import Path

from stockdex import config

ROOT = Path(__file__).resolve().parents[1]
TARGET = (
    ROOT / "plugins" / "stockdex" / "skills" / "stockdex" / "reference" / "metrics.md"
)
SECTIONS = (
    ("income_statement", "INCOME_STATEMENT_COLUMNS"),
    ("cash_flow", "CASH_FLOW_COLUMNS"),
    ("balance_sheet", "BALANCE_SHEET_COLUMNS"),
)


def render() -> str:
    lines = [
        "# Financial statement metrics",
        "",
        "<!-- Generated by scripts/generate_skill_metrics.py; do not edit. -->",
        "",
        "Pass these names, unprefixed and case-sensitive, in the `metrics`",
        "argument of `get_financial_statement` for the matching `statement`.",
        "Output columns carry an `annual`/`quarterly` prefix.",
    ]
    for statement, attribute in SECTIONS:
        lines += ["", f"## {statement}", ""]
        lines += [f"- {name}" for name in sorted(getattr(config, attribute))]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render())
    print(f"wrote {TARGET.relative_to(ROOT)}")
